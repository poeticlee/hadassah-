#!/usr/bin/env node
/**
 * Generates public/sitemap.xml from the product catalogue so new products are
 * always listed without a manual edit.
 */
import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { PRODUCTS } from '../src/data/products.js'
import { SITE_URL } from '../src/data/site.js'

const PRIORITY = {
  '/': '1.0',
  '/products': '0.9',
  '/custom-branding': '0.8',
  '/gallery': '0.7',
  '/contact': '0.7',
  '/faq': '0.6',
  '/privacy': '0.3',
}

const PAGES = [
  { route: '/', freq: 'weekly' },
  { route: '/products', freq: 'weekly' },
  { route: '/custom-branding', freq: 'monthly' },
  { route: '/gallery', freq: 'monthly' },
  { route: '/faq', freq: 'monthly' },
  { route: '/contact', freq: 'monthly' },
  { route: '/privacy', freq: 'yearly' },
  ...PRODUCTS.map((p) => ({ route: `/products/${p.slug}`, freq: 'monthly' })),
]

const lastmod = new Date().toISOString().slice(0, 10)

const entries = PAGES.map(
  ({ route, freq }) => `  <url>
    <loc>${SITE_URL}${route}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${freq}</changefreq>
    <priority>${PRIORITY[route] ?? '0.6'}</priority>
  </url>`,
).join('\n')

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries}
</urlset>
`

await writeFile(path.join(process.cwd(), 'public', 'sitemap.xml'), xml, 'utf8')
console.log(`✓ sitemap.xml — ${PAGES.length} urls @ ${SITE_URL}`)
